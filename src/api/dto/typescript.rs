//! The bodies above, and the domain types the API sends as they are, written out as TypeScript
//! for the web UI, which checks its own types against them. Running the tests writes
//! `web/src/infrastructure/node_wire.ts`, which is never committed: `npm run check` writes it
//! afresh before type-checking, so a change to a body fails it until the UI follows.
//!
//! The types derive `TS` only under test, so `ts-rs` is a dev-dependency and never in the node.
//! Nothing here touches serde: the JSON stays exactly as it was.

use std::fs;
use std::path::Path;

use ts_rs::{Config, TS};

use super::*;
use crate::domain::accounting::transaction::Transaction;
use crate::domain::accounting::{Coins, Destination, Memo, Source};
use crate::domain::chain::block::{
    Block, BlockHash, BlockHeader, MerkleNode, MerkleRoot, Side, Step,
};
use crate::domain::consensus::{Beacon, BlockCapacity, Commitment, Reveal};
use crate::domain::crypto::{Address, Signature};

/// Where the UI keeps it, beside the adapter that talks to the node.
const OUTPUT: &str = "web/src/infrastructure/node_wire.ts";

const HEADER: &str = "\
// The node's request and response bodies, as the Rust code declares them: what the HTTP adapter
// checks the application's types against. Generated by `cargo test` from src/api/dto/typescript.rs;
// don't edit it by hand.
";

// Value objects go over the wire as the plain string or number inside them, so they are written
// as that type, not as a type of their own.
macro_rules! on_the_wire_as {
    ($($value:ty => $wire:ty),* $(,)?) => {$(
        impl TS for $value {
            type WithoutGenerics = Self;
            type OptionInnerType = Self;
            fn name(cfg: &Config) -> String {
                <$wire as TS>::name(cfg)
            }
            fn inline(cfg: &Config) -> String {
                <$wire as TS>::inline(cfg)
            }
        }
    )*};
}

on_the_wire_as! {
    Address => String,
    Signature => String,
    Source => String,
    Destination => String,
    BlockHash => String,
    MerkleRoot => String,
    MerkleNode => String,
    Commitment => String,
    Memo => String,
    Reveal => String,
    Beacon => String,
    Coins => u64,
    BlockCapacity => Option<u64>,
}

/// Every declaration, in the order the file lists them: the bodies, part by part as `dto` splits
/// them, then the domain types the API sends as they are.
fn declarations(cfg: &Config) -> Vec<String> {
    let all: &[fn(&Config) -> String] = &[
        declaration::<StatusResponse>,
        declaration::<ValidityResponse>,
        declaration::<ReplaceResponse>,
        declaration::<MineRequest>,
        declaration::<ForgeRequest>,
        declaration::<ProposalRequest>,
        declaration::<ConsensusResponse>,
        declaration::<StakeEntry>,
        declaration::<SignRequest>,
        declaration::<TransactionResponse>,
        declaration::<PlacementResponse>,
        declaration::<ProofResponse>,
        declaration::<FeesResponse>,
        declaration::<BlockFeesEntry>,
        declaration::<WalletResponse>,
        declaration::<BalanceResponse>,
        declaration::<PeerRequest>,
        declaration::<PeerResponse>,
        declaration::<AddPeerResponse>,
        declaration::<SyncResponse>,
        declaration::<NodeResponse>,
        declaration::<ErrorResponse>,
        undocumented::<Block>,
        undocumented::<BlockHeader>,
        undocumented::<Transaction>,
        declaration::<Step>,
        declaration::<Side>,
    ];
    all.iter().map(|declare| declare(cfg)).collect()
}

fn declaration<T: TS>(cfg: &Config) -> String {
    format!("{}{}", T::docs().unwrap_or_default(), undocumented::<T>(cfg))
}

/// Without the type's own doc comment, for domain types whose docs are about who may change them
/// in Rust, with doctests to prove it, which mean nothing in TypeScript. Their fields keep theirs.
fn undocumented<T: TS>(cfg: &Config) -> String {
    format!("export {}\n", T::decl(cfg))
}

/// The whole file. Every whole number the node sends is a JSON number, so `u64` is `number`, not
/// ts-rs's default `bigint`. Those that could outgrow one are sent as strings instead.
fn node_wire() -> String {
    let cfg = Config::new().with_large_int("number");
    format!("{HEADER}\n{}", declarations(&cfg).join("\n"))
}

#[test]
fn writes_the_node_wire_types_for_the_web_ui() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(OUTPUT);
    let wire = node_wire();
    if fs::read_to_string(&path).ok().as_deref() != Some(wire.as_str()) {
        fs::write(&path, wire).expect("the web UI's folder is writable");
    }
}

#[test]
fn says_number_for_every_amount_and_string_for_every_value_object() {
    let wire = node_wire();
    assert!(!wire.contains("bigint"), "{wire}");
    for wrapper in ["Address", "Coins", "BlockHash", "MerkleNode", "Signature", "Reveal"] {
        assert!(!wire.contains(&format!(": {wrapper}")), "{wrapper} isn't inlined:\n{wire}");
    }
}
